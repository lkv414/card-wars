// scripts/seed-mechanics.mjs
// Reads scripts/parse_mechanics.py output (исходники/cards.with_mechanics.json)
// and generates SQL UPDATEs that load the structured `mechanics` into public.cards
// matched by card_number (handles duplicate physical cards via card_numbers[]).
//
// Usage:  node scripts/seed-mechanics.mjs
// Output: supabase/seed/mechanics_data.sql  (apply via `psql` / Supabase SQL editor)

import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, "..")

const SRC = resolve(ROOT, "исходники/cards.with_mechanics.json")
const OUT = resolve(ROOT, "supabase/seed/mechanics_data.sql")

function cardNumbers(entry) {
  const nums = new Set()
  if (Array.isArray(entry.card_numbers)) {
    for (const n of entry.card_numbers) nums.add(Number(n))
  }
  if (entry.card_number !== undefined && entry.card_number !== null) {
    nums.add(Number(entry.card_number))
  }
  return [...nums].filter((n) => Number.isFinite(n))
}

function main() {
  const raw = JSON.parse(readFileSync(SRC, "utf8"))
  const cards = Array.isArray(raw) ? raw : Object.values(raw)

  const lines = []
  lines.push("-- Generated by scripts/seed-mechanics.mjs — DO NOT EDIT BY HAND")
  lines.push("-- Loads parsed structured mechanics into public.cards.mechanics")
  lines.push("")

  let updated = 0
  let skipped = 0

  for (const entry of cards) {
    const nums = cardNumbers(entry)
    const mechanics = entry.mechanics
    if (nums.length === 0) {
      skipped++
      continue
    }
    if (!Array.isArray(mechanics)) {
      skipped++
      continue
    }
    const payload = JSON.stringify(mechanics)
    // $mech$ dollar-quoting avoids escaping issues with single quotes / unicode.
    const arr = nums.join(", ")
    lines.push(
      `UPDATE public.cards SET mechanics = $mech$${payload}$mech$ ` +
        `WHERE card_number = ANY(ARRAY[${arr}]);`
    )
    updated++
  }

  lines.push("")
  lines.push(`-- summary: updated=${updated} skipped=${skipped} total_cards=${cards.length}`)

  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, lines.join("\n"), "utf8")
  console.log(`Wrote ${OUT}`)
  console.log(`updated=${updated} skipped=${skipped} total=${cards.length}`)
}

main()
