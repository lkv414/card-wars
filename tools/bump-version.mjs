// Dynamic version bumper and synchronizer for Card Wars v3.
// Usage:
//   node tools/bump-version.mjs [auto|patch|minor|major|sync|set <version>]
//
// Updates:
//   - root package.json ("version": "x.y.z")
//   - apps/client/package.json ("version": "x.y.z")
//   - apps/client/src/version.ts (exports APP_VERSION, BUILD_TIME, GIT_COMMIT)
//   - apps/client/public/sw.js (const CACHE_VERSION = 'v<x.y.z>')
//   - apps/client/dist/sw.js (if dist exists)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function writeJson(path, data) {
  writeFileSync(path, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
}

function getGitCommit() {
  try {
    return execSync('git rev-parse --short HEAD', { cwd: root, encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
}

function getGitCommitCount() {
  try {
    // Check if shallow clone (often in CI/Cloudflare)
    try {
      const isShallow = execSync('git rev-parse --is-shallow-repository', { cwd: root, encoding: 'utf8' }).trim() === 'true';
      if (isShallow) {
        try { execSync('git fetch --unshallow', { cwd: root, stdio: 'ignore' }); } catch {}
      }
    } catch {}
    const count = Number(execSync('git rev-list --count HEAD', { cwd: root, encoding: 'utf8' }).trim());
    if (Number.isFinite(count) && count > 0) return count;
  } catch {}
  return null;
}

const rootPkgPath = join(root, 'package.json');
const clientPkgPath = join(root, 'apps/client/package.json');
const versionTsPath = join(root, 'apps/client/src/version.ts');
const swPath = join(root, 'apps/client/public/sw.js');
const distSwPath = join(root, 'apps/client/dist/sw.js');

const rootPkg = readJson(rootPkgPath);
let currentVersion = rootPkg.version || '3.1.0';

const args = process.argv.slice(2);
const command = args[0] || 'auto';

let newVersion = currentVersion;

const semverRegex = /^(\d+)\.(\d+)\.(\d+)(?:-([0-9A-Za-z.-]+))?$/;
const match = currentVersion.match(semverRegex);

if (!match && command !== 'set') {
  console.error(`Invalid current version: ${currentVersion}`);
  process.exit(1);
}

const major = match ? Number(match[1]) : 3;
const minor = match ? Number(match[2]) : 1;
const patch = match ? Number(match[3]) : 0;

if (command === 'auto') {
  const commitCount = getGitCommitCount();
  if (commitCount != null && commitCount > 0) {
    newVersion = `${major}.${minor}.${commitCount}`;
  } else {
    newVersion = currentVersion;
  }
} else if (command === 'patch') {
  newVersion = `${major}.${minor}.${patch + 1}`;
} else if (command === 'minor') {
  newVersion = `${major}.${minor + 1}.0`;
} else if (command === 'major') {
  newVersion = `${major + 1}.0.0`;
} else if (command === 'set') {
  const target = args[1];
  if (!target || !semverRegex.test(target)) {
    console.error(`Usage: node tools/bump-version.mjs set <x.y.z>`);
    process.exit(1);
  }
  newVersion = target;
} else if (command === 'sync') {
  newVersion = currentVersion;
} else {
  console.error(`Unknown command: ${command}. Use auto, patch, minor, major, sync, or set <version>`);
  process.exit(1);
}

const gitCommit = getGitCommit();
const buildTime = new Date().toISOString();
const formattedAppVersion = `v${newVersion}`;

console.log(`Version: ${currentVersion} -> ${newVersion} (${command}, git ${gitCommit})`);

// 1. Update root package.json
rootPkg.version = newVersion;
writeJson(rootPkgPath, rootPkg);

// 2. Update apps/client/package.json
if (existsSync(clientPkgPath)) {
  const clientPkg = readJson(clientPkgPath);
  clientPkg.version = newVersion;
  writeJson(clientPkgPath, clientPkg);
}

// 3. Write apps/client/src/version.ts
const versionTsContent = `// Auto-generated by tools/bump-version.mjs. Do not edit manually.
export const APP_VERSION = '${formattedAppVersion}';
export const BUILD_TIME = '${buildTime}';
export const GIT_COMMIT = '${gitCommit}';
`;
writeFileSync(versionTsPath, versionTsContent, 'utf8');

// 4. Update apps/client/public/sw.js
if (existsSync(swPath)) {
  let swContent = readFileSync(swPath, 'utf8');
  const cacheVersionRegex = /const CACHE_VERSION = ['"][^'"]+['"];/;
  if (cacheVersionRegex.test(swContent)) {
    swContent = swContent.replace(cacheVersionRegex, `const CACHE_VERSION = '${formattedAppVersion}';`);
    writeFileSync(swPath, swContent, 'utf8');
  }
}

// 5. Update apps/client/dist/sw.js if dist exists
if (existsSync(distSwPath)) {
  let distSwContent = readFileSync(distSwPath, 'utf8');
  const cacheVersionRegex = /const CACHE_VERSION = ['"][^'"]+['"];/;
  if (cacheVersionRegex.test(distSwContent)) {
    distSwContent = distSwContent.replace(cacheVersionRegex, `const CACHE_VERSION = '${formattedAppVersion}';`);
    writeFileSync(distSwPath, distSwContent, 'utf8');
  }
}

console.log(`✓ Synchronized version ${formattedAppVersion} across package.json, version.ts, and sw.js`);
